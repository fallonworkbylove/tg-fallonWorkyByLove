      /(обидно|я жив|не бот|не ии|похожа на|с чего ты взял|часто с ии|хах\s+(ну\s+ты|опять)|зациклил|ладно\s+верь|странно\s+звучит|никто\s+ещё|общаюсь\s+как\s+могу)/i.test(
        recentBot,
      );

