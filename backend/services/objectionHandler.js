  /переез|перебир|еду\s+в|поеду\s+в|буду\s+(?:жить\s+)?в|к\s+маме|нижн\w*\s+новгород|анап|липецк|донецк|белгород/i;

function lastAssistantMentionedMove(history) {
  const recent = Array.isArray(history) ? history : [];
  for (let i = recent.length - 1; i >= 0; i -= 1) {
    const h = recent[i];
    if (!h) continue;
    if (h.role === 'user') continue;
    if (h.role === 'assistant') {
      return MOVE_CONTEXT_RE.test(String(h.content || ''));
    }
    break;
  }
  return false;
}

