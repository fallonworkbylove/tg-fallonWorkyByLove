  if (
    /^(?:а\s+|ну\s+)?(?:сколько|скок)\s*[?)!]?\s*$/i.test(String(text || '').trim()) &&
    recentFlipPhotoInHistory(history) &&
    !CONTACT_REQUEST_RE.test(text)
  ) {
    return getEarningsAskHint();
  }

